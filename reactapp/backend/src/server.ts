import http from 'node:http';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import { Server } from 'socket.io';
import { config } from './config.js';
import products from './routes/products.js';
import stock from './routes/stock.js';
import reorders from './routes/reorders.js';
import { errorHandler, notFound } from './middleware.js';
import { setSocketServer } from './services/notifications.js';

const app=express();
app.use(helmet());
app.use(cors({origin:config.clientOrigin}));
app.use(express.json({limit:'1mb'}));
app.use(morgan(config.nodeEnv==='production'?'combined':'dev'));
app.get('/health', (_req,res)=>res.json({status:'ok',service:'inventory-api'}));
app.use('/api/products',products);
app.use('/api/stock',stock);
app.use('/api/reorders',reorders);
app.use(notFound);
app.use(errorHandler);
const httpServer=http.createServer(app);
const io=new Server(httpServer,{cors:{origin:config.clientOrigin}});
setSocketServer(io);
io.on('connection',(socket)=>socket.emit('connected',{message:'Inventory notifications connected'}));
httpServer.listen(config.port,()=>console.log(`Inventory API listening on http://localhost:${config.port}`));
